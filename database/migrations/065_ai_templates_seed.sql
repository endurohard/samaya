-- 065_ai_templates_seed.sql
--
-- Стартовый набор шаблонов для клиники «Самая».
--
-- Тексты черновые: их правит владелец в админке (Настройки → AI ассистент).
-- Заводим их миграцией, а не оставляем пустой список, по двум причинам:
-- пустой раздел не объясняет, как писать описания для классификатора, и
-- проверить работу ассистента до первого собственного шаблона нельзя.
--
-- Автоотправка включена ТОЛЬКО там, где ошибиться нечем и текст не зависит
-- от обстоятельств: приветствие, благодарность, адрес, режим работы.
-- Цена, запись, медицина, жалобы — всегда через человека, даже когда тема
-- определена уверенно.
--
-- Описания (matcher) написаны по одному правилу: что входит, что НЕ входит,
-- и пример. Это формат, который классификатор читает лучше всего, и именно
-- на него ориентируется владелец, добавляя свои темы.

SET search_path TO ai, public;

INSERT INTO reply_templates (company_id, topic, title, matcher, body, autosend, sort_order)
SELECT c.id, v.topic, v.title, v.matcher, v.body, v.autosend, v.sort_order
FROM users.companies c
CROSS JOIN (VALUES
  ('greeting', 'Приветствие', 10, TRUE,
   'Приветствие или начало разговора без вопроса: «Здравствуйте», «Добрый день», «Можно вопрос?». НЕ сюда, если вместе с приветствием задан любой вопрос — тогда тема определяется по вопросу.',
   'Здравствуйте! Рады вас видеть. Подскажите, что вас интересует — услуга, стоимость или запись?'),

  ('hours', 'Режим работы', 20, TRUE,
   'Вопрос о часах работы, рабочих днях, выходных, праздниках: «до скольки работаете», «вы открыты в воскресенье», «когда можно подойти». НЕ сюда вопрос о свободном времени для записи — это booking.',
   'Мы работаем ежедневно с 10:00 до 20:00, без выходных. Будем рады вас видеть.'),

  ('address', 'Адрес и как добраться', 30, TRUE,
   'Вопрос о местоположении, адресе, маршруте, парковке, ориентирах: «где вы находитесь», «как доехать», «есть ли парковка».',
   'Мы находимся в Каспийске, ул. Ленина, 18. Рядом есть парковка. Если будет сложно найти — позвоните, подскажем дорогу.'),

  ('thanks', 'Благодарность', 40, TRUE,
   'Благодарность или завершение разговора без нового вопроса: «спасибо», «всё поняла», «хорошо, до встречи».',
   'Спасибо вам! Будем рады видеть вас в клинике. Если появятся вопросы — пишите.'),

  ('price', 'Стоимость услуг', 50, FALSE,
   'Вопрос о стоимости услуги, прайсе, акциях, рассрочке: «сколько стоит чистка», «какие цены на уходы». НЕ сюда споры об уже уплаченной сумме и возвраты — это complaint. НЕ сюда вопросы, в которых вместе с ценой спрашивают про показания или подойдёт ли процедура — это medical.',
   'Стоимость зависит от объёма работы и подбирается на консультации. Напишите, какая услуга вас интересует, — администратор назовёт точную цену.'),

  ('booking', 'Запись на приём', 60, FALSE,
   'Клиент хочет записаться или спрашивает о свободном времени без признаков срочности: «хочу записаться на четверг», «есть ли места на следующей неделе». НЕ сюда, если нужно «сегодня» или «срочно» — это urgent.',
   'Конечно, запишем. Подскажите, пожалуйста, на какую услугу и какой день вам удобен — администратор подтвердит время.'),

  ('urgent', 'Срочная запись', 70, FALSE,
   'Запись или вопрос с явной срочностью: «сегодня», «срочно», «через час», «прямо сейчас». Шаблон не знает расписания, поэтому такие сообщения всегда идут администратору.',
   'Уточняю свободное время у администратора — ответим вам в ближайшие минуты.'),

  ('medical', 'Вопрос о здоровье', 80, FALSE,
   'Любой вопрос о здоровье, показаниях, противопоказаниях, совместимости с заболеванием, болевых ощущениях, сроках заживления, осложнениях, а также фото проблемы или результата. Имеет приоритет над price и booking, если в сообщении есть и то и другое. Пример: «у меня розацеа, можно лазер?», «что за пятно после процедуры?».',
   'Спасибо за вопрос. На такие вопросы отвечает врач — заочно оценивать не возьмёмся, чтобы не навредить. Приходите на консультацию, врач осмотрит и всё подробно расскажет.'),

  ('complaint', 'Жалоба или возврат', 90, FALSE,
   'Недовольство результатом или обслуживанием, требование вернуть деньги, конфликт, угроза отзывом, спор об уплаченной сумме.',
   'Очень жаль, что так вышло. Передаю ваше обращение руководителю — он свяжется с вами лично, чтобы разобраться.'),

  ('jobs', 'Вакансии', 100, FALSE,
   'Вопрос о работе, вакансиях, резюме, сотрудничестве как специалиста. Это не клиентский запрос.',
   'Спасибо за интерес к нашей клинике! Пришлите, пожалуйста, резюме — передадим руководителю, и мы вернёмся с ответом.')
) AS v(topic, title, sort_order, autosend, matcher, body)
WHERE NOT EXISTS (
  SELECT 1 FROM reply_templates t
   WHERE t.company_id = c.id AND t.topic = v.topic
);
