-- 071_ai_price_quote_texts.sql
--
-- Служебные тексты ценового ответа — в шаблоны, чтобы владелец правил их в
-- админке, а не коммитом.
--
-- Что было: приветствие, переспросы («Спасибо! Остался один вопрос»),
-- заголовок ответа, строка «Итого» и хвост («процедура без наркоза»,
-- «записаться на консультацию») лежали литералами в price.ts. Правило
-- «цену нельзя сочинить» по инерции распространили на весь ответ целиком,
-- хотя это обычные фразы клиники, а не числа. Владелец правил шаблон в
-- админке и не видел изменений — выглядело как баг сохранения.
--
-- Цены зон остаются в коде: их выдумать по-прежнему нечем.
--
-- Эта тема НЕ участвует в классификации (см. SERVICE_TOPICS в
-- classifier.ts): в её теле лежит размеченная рыба, а не ответ клиенту.
-- Классификатору её показывать нельзя, иначе модель выберет её темой и
-- клиент получит «заголовок: Стоимость…» вместо цены.

SET search_path TO ai, public;

INSERT INTO ai.reply_templates (company_id, topic, title, matcher, body, autosend, enabled, sort_order)
SELECT
  c.company_id,
  'price_quote_texts',
  'Служебные тексты ответа о цене',
  'Служебная тема: не выбирается классификатором, хранит куски текста ценового ответа.',
  E'заголовок: Стоимость лазерной липосакции — {city}:\n'
  || E'итого: Итого: {total}\n'
  || E'переспрос-один: Спасибо! Остался один вопрос:\n'
  || E'переспрос-много: Спасибо! Уточните, пожалуйста:\n'
  || E'хвост:\n'
  || E'Процедура проходит под местной анестезией, без общего наркоза 🤍\n'
  || E'Подскажите, вам удобнее записаться на консультацию или остались вопросы?',
  FALSE,
  TRUE,
  900
FROM (SELECT DISTINCT company_id FROM ai.reply_templates) c
ON CONFLICT (company_id, topic) DO NOTHING;
