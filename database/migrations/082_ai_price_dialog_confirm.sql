-- Подтверждение прежних города и веса в течение недели.
--
-- Задача владельца: клиент вернулся через несколько дней с новым вопросом
-- о цене — не спрашивать город и вес заново с нуля, а уточнить, не
-- изменились ли они. Ответил «да, всё верно» — считаем по прежним; назвал
-- новые — пересчитываем по новым.
--
-- Почему нужна отдельная колонка, а не только TTL: состояние разговора
-- живёт сутки и после этого забывается целиком. Город и вес должны
-- пережить этот срок (до недели), но ТОЛЬКО как «данные к подтверждению»,
-- а не как готовые к расчёту. Без явного признака ассистент назвал бы цену
-- по весу недельной давности, которого клиент не подтверждал.
--
-- confirm_asked_at — момент, когда задан вопрос «город и вес прежние?».
-- Пока он стоит, короткий ответ («да», «всё так», «нет, 80») разбирается
-- как подтверждение, а не как новый вопрос.
ALTER TABLE ai.price_dialog
  ADD COLUMN IF NOT EXISTS confirm_asked_at timestamptz;

COMMENT ON COLUMN ai.price_dialog.confirm_asked_at IS
  'когда спросили «город и вес прежние?» — пока стоит, ответ читается как подтверждение';
