-- 074_ai_thread_intro.sql
--
-- Отметка «вступление в этот диалог уже отправляли».
--
-- Зачем: вступление с фотографиями зон ног отправляется ОДИН раз на
-- разговор. Клиент называет ноги по нескольку раз подряд («ноги», потом
-- «круговая», потом «Москва, 70, ноги»), и повторная пара одинаковых
-- картинок читается как зациклившийся бот.
--
-- Отдельная таблица, а не колонка в ai.price_dialog: вступление не
-- привязано к ценовому опроснику и переживает его срок жизни (сутки).
-- Клиент, вернувшийся через неделю, вопросы о цене получит заново, а
-- схемы зон второй раз — нет, он их уже видел.

SET search_path TO ai, public;

CREATE TABLE IF NOT EXISTS ai.thread_intro (
  company_id uuid        NOT NULL,
  channel    text        NOT NULL,
  thread_id  text        NOT NULL,
  -- Ключ вступления = тема-хранилище его текста. Сценариев «покажи
  -- картинки и объясни» со временем будет больше одного.
  intro_key  text        NOT NULL,
  sent_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (company_id, channel, thread_id, intro_key)
);
