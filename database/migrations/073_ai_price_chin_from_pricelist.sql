-- 073_ai_price_chin_from_pricelist.sql
--
-- Цены в тексте шаблона «Цена: подбородок и овал лица» — на подстановку из
-- прайса.
--
-- Что было: суммы 150 000 / 200 000 ₽ написаны прямо в теле шаблона, и это
-- второй источник правды рядом с ai.price_zones. Владелец правит цену
-- подбородка в прайсе, ассистент продолжает отвечать старой суммой из
-- текста, и расхождение всплывает уже в переписке с клиенткой.
--
-- Решение: метка {цена:chin:каспийск} вместо числа. Подстановку делает
-- renderPrices() при сборке ответа, источник — та же таблица, что у
-- опросника. Остальной текст (рассказ про Contour Lift) остаётся как есть
-- и правится в админке.
--
-- Замена точечная, через replace по известной строке: переписывать тело
-- целиком нельзя — владелец мог править текст после прошлой выкладки, и
-- INSERT ... DO UPDATE затёр бы его правки.

SET search_path TO ai, public;

UPDATE ai.reply_templates
   SET body = replace(
         replace(body, '• Каспийск — 150 000 ₽', '• Каспийск — {цена:chin:каспийск}'),
         '• Москва — 200 000 ₽', '• Москва — {цена:chin:москва}')
 WHERE topic = 'price_chin'
   AND body LIKE '%150 000 ₽%';
