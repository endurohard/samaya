-- 075_ai_legs_intro.sql
--
-- Вступление про круговую лазерную липосакцию ног: два текста и две схемы
-- зон между ними.
--
-- Тексты в шаблоне, а не в коде: это то, что клиника говорит клиенту от
-- своего имени, и править их владелец должен в админке.
--
-- Разметка частей строками «--- текст» / «--- фото: имя» вместо JSON:
-- владелец правит тело шаблона руками, и сломанный JSON убил бы ответ
-- целиком, а лишняя строка разметки — максимум одну часть.
--
-- Имена фотографий (legs-zones-front, legs-zones-back) — файлы, лежащие
-- рядом с сервисом канала (instagram-service/assets). В шаблоне имя, а не
-- ссылка: публичная ссылка на вложение подписана и живёт 15 минут, а
-- схемы зон одни и те же месяцами.
--
-- Тема служебная — она НЕ участвует в классификации (см. SERVICE_TOPICS в
-- classifier.ts): иначе модель выберет её на обычном вопросе о цене, и
-- клиент получит размеченную рыбу вместо ответа.

SET search_path TO ai, public;

INSERT INTO ai.reply_templates (company_id, topic, title, matcher, body, autosend, enabled, sort_order)
SELECT
  c.company_id,
  'legs_intro',
  'Вступление: круговая липосакция ног (2 фото)',
  'Служебная тема: не выбирается классификатором. Хранит тексты и порядок частей вступления про круговую липосакцию ног.',
  E'--- текст\n'
  || E'Круговая лазерная липосакция ног — это уникальная процедура, и доктор подходит к каждому пациенту индивидуально. Поскольку методика подходит не всем, нам важно сначала увидеть исходные формы и понять, сможем ли мы помочь именно в вашем случае.\n'
  || E'\n'
  || E'Пришлите, пожалуйста, фото ног прямо, сбоку и со спины — доктор проконсультирует и скажет будет ли эффективная наша процедура 🤍\n'
  || E'--- фото: legs-zones-front\n'
  || E'--- фото: legs-zones-back\n'
  || E'--- текст\n'
  || E'Уникальная авторская методика, по которой мы работаем комплексно, равномерно прорабатывая все 7 зон ног, а не отдельные участки.\n'
  || E'\n'
  || E'Мы создаем плавные переходы без резких границ, чтобы сформировать красивый, гармоничный силуэт со всех сторон.\n'
  || E'\n'
  || E'При комплексной проработке меняется не только контур ног — ягодицы визуально становятся более округлыми, а силуэт приобретает более женственные пропорции.\n'
  || E'\n'
  || E'❗️Процедура проводится без общего наркоза и без тяжёлой реабилитации❗️\n'
  || E'\n'
  || E'После процедуры вы самостоятельно встаёте и уходите домой на своих уже худых ножках 💃\n'
  || E'\n'
  || E'Выше показали, какие именно 7 зон входят в процедуру 🤍',
  TRUE,
  TRUE,
  910
FROM (SELECT DISTINCT company_id FROM ai.reply_templates) c
ON CONFLICT (company_id, topic) DO NOTHING;
