-- 057_client_medcard.sql
--
-- Мед.карта клиента: результаты анализов с датой сдачи и комментарием врача.
--
-- Контекст: в клинике делают операции (лазерная липосакция), анализы копятся
-- по клиенту годами, и врачу важна ДИНАМИКА — посмотреть, как показатели
-- менялись от сдачи к сдаче. Поэтому ключевое поле здесь taken_at, а не
-- created_at: файл нередко загружают через недели после сдачи (или это делает
-- сам клиент через личный кабинет), и хронология по дате загрузки врала бы.
--
-- Расширяем существующую clients.client_files, а не заводим отдельную таблицу:
-- анализ — это и есть файл клиента (PDF/фото). Отдельная таблица заставила бы
-- дублировать хранение bytea, выдачу файла и портал самозагрузки, а карточка
-- всё равно показывала бы два списка вместо одного.
--
-- Сознательно БЕЗ разделения на типы файлов: отдельного потока документов у
-- клиники нет, все файлы клиента — это мед.карта. Тип разъединил бы файлы,
-- присланные клиентом через портал (он про типы ничего не знает), и те, что
-- завёл врач, — и присланное клиентом просто не попало бы в мед.карту.
--
--   taken_at    — дата сдачи анализа; по ней строится хронология.
--   title       — что за анализ («Общий анализ крови»): имя файла обычно
--                 нечитаемое (scan_20260915.pdf).
--   doctor_note — заключение врача по результату.

SET search_path TO clients, public;

ALTER TABLE client_files
  ADD COLUMN IF NOT EXISTS taken_at    DATE,
  ADD COLUMN IF NOT EXISTS title       TEXT,
  ADD COLUMN IF NOT EXISTS doctor_note TEXT;

-- Список в карточке отсортирован по дате сдачи (новые сверху). Индекс по
-- taken_at без выражения: COALESCE(taken_at, created_at::date) в индекс не
-- берётся — приведение timestamptz→date зависит от таймзоны сессии и потому
-- не IMMUTABLE. Сортировку с COALESCE делает сам запрос, а этот индекс
-- покрывает выборку файлов клиента.
CREATE INDEX IF NOT EXISTS idx_client_files_taken
  ON client_files(client_id, company_id, taken_at DESC NULLS LAST);

COMMENT ON COLUMN client_files.taken_at IS
  'Дата сдачи анализа (не загрузки файла) — по ней строится динамика';
COMMENT ON COLUMN client_files.doctor_note IS
  'Заключение врача по результату анализа';
