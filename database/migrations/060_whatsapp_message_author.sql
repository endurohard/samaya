-- Кто из сотрудников отправил сообщение.
--
-- Номер WhatsApp у клиники один, а работают за ним посменно несколько человек.
-- В переписке все исходящие выглядели одинаково («Мы»), и по истории нельзя
-- было понять, кто именно что обещал клиенту.
--
-- NULL означает «автор неизвестен» и это нормальное значение:
--   * у всех сообщений, записанных до этой миграции;
--   * у напоминаний и поздравлений — их шлёт booking-service по расписанию,
--     сотрудника за ними нет.
-- Поэтому колонка nullable: проставить задним числом нечего, а выдумывать
-- автора для старых записей — врать в истории переписки.
--
-- ON DELETE SET NULL: уволенный сотрудник удаляется из users, но его
-- переписка с клиентами остаётся — терять её нельзя.

ALTER TABLE whatsapp.messages
  ADD COLUMN IF NOT EXISTS author_id   UUID REFERENCES users.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS author_name TEXT;

-- Имя копией рядом с ссылкой: сотрудник может уволиться и исчезнуть из users,
-- а в истории переписки подпись «Магомедова Наида» должна остаться. Джойн к
-- users такого не даёт — после удаления осталось бы пустое место.

COMMENT ON COLUMN whatsapp.messages.author_id IS
  'Сотрудник, отправивший сообщение. NULL — автоматика или сообщение до внедрения подписи.';
COMMENT ON COLUMN whatsapp.messages.author_name IS
  'Имя автора на момент отправки. Хранится копией, чтобы подпись пережила увольнение.';
