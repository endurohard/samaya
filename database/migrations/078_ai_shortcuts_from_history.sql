-- Тексты быстрых шаблонов взяты из РЕАЛЬНОЙ переписки Instagram: эти
-- формулировки менеджеры отправляли клиентам сотнями раз (от 86 до 563
-- отправок за два месяца), то есть они уже обкатаны и согласованы.
-- Сочинять их заново было бы хуже вдвойне: текст уходит клиенту от имени
-- клиники, и выдуманная формулировка разошлась бы с тем, что говорят живые
-- менеджеры в соседнем диалоге.
--
-- Цены в текстах про живот и руки оставлены как есть, числом: эти шаблоны
-- менеджер отправляет руками, и подстановка {цена:...} работает только для
-- зон, которые есть в прайсе ассистента. Живот с четырьмя ступенями по весу
-- одной суммой не описывается — для него у ассистента есть опросник.
--
-- Обновляем ТОЛЬКО незаполненные заготовки (условие по body): владелец мог
-- успеть вписать свой текст между выкладками, и затирать его нельзя.

