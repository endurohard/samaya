-- Отдельное хранение данных к подтверждению (исправление к 082).
--
-- В 082 город и вес к подтверждению брались из ТЕХ ЖЕ колонок city/weight,
-- что и живое состояние разговора, а сохранение не давало их очистить
-- (COALESCE). Два следствия, оба проверены на бою:
--
--  1. Требование «новый вопрос о цене — уточнить всё заново» переставало
--     работать: ассистент задавал вопрос, но в строке оставались прежний
--     город и вес, и следующее сообщение считалось по данным, которых
--     клиент в этом разговоре не подтверждал.
--  2. Недельный срок считался от updated_at, а он обновляется на КАЖДОМ
--     сообщении — прошлые данные жили сколько угодно, лишь бы клиент
--     продолжал писать.
--
-- Теперь это две независимые вещи:
--   city/weight     — живое состояние, очищается честно;
--   prior_*         — снимок последних известных данных, только для
--                     вопроса «прежние?», со своей отметкой времени.
ALTER TABLE ai.price_dialog
  ADD COLUMN IF NOT EXISTS prior_city   text,
  ADD COLUMN IF NOT EXISTS prior_weight numeric,
  ADD COLUMN IF NOT EXISTS prior_at     timestamptz;

-- Перенос того, что уже накоплено: у живых строк город и вес становятся
-- снимком. Без этого клиенты, писавшие до выката, потеряли бы данные и
-- получили бы опрос с нуля.
UPDATE ai.price_dialog
   SET prior_city   = city,
       prior_weight = weight,
       prior_at      = updated_at
 WHERE prior_at IS NULL
   AND (city IS NOT NULL OR weight IS NOT NULL);

COMMENT ON COLUMN ai.price_dialog.prior_city IS
  'снимок города для вопроса «прежние?» — в расчёт идёт только после подтверждения';
COMMENT ON COLUMN ai.price_dialog.prior_weight IS
  'снимок веса для вопроса «прежние?» — в расчёт идёт только после подтверждения';
COMMENT ON COLUMN ai.price_dialog.prior_at IS
  'когда сделан снимок; от него считается недельный срок, а не от updated_at';
