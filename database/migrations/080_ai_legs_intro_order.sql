-- Вступление про круговую липосакцию ног: сначала схемы зон, потом тексты.
--
-- Порядок задан владельцем: клиент должен СНАЧАЛА увидеть, какие именно
-- 7 зон прорабатываются, потом прочитать про методику, затем получить
-- просьбу прислать свои фото, и только после этого — цену. Прежний шаблон
-- начинался с просьбы о фото, то есть просил человека сфотографироваться
-- раньше, чем объяснял, что за процедура.
--
-- Фотографии идут ПЕРЕД текстом про 7 зон, а не после: текст заканчивается
-- словами «Выше покажем, какие именно 7 зон входят в процедуру», и при
-- обратном порядке эта строка указывала бы в пустоту — в Direct новые
-- сообщения появляются ниже предыдущих.
--
-- Тексты — дословно от владельца, без переформулирования: автоответчик
-- отдаёт тела шаблонов как есть, и правка формулировки здесь ушла бы
-- клиенту от имени клиники.
--
-- Условие WHERE защищает ручные правки: если владелец уже переписал тело
-- через админку, миграция его не тронет.
UPDATE ai.reply_templates
   SET body = E'--- фото: legs-zones-front\n'
           || E'--- фото: legs-zones-back\n'
           || E'--- текст\n'
           || E'Уникальная авторская методика, по которой мы работаем комплексно, равномерно прорабатывая все 7 зон ног, а не отдельные участки.\n\n'
           || E'Мы создаем плавные переходы без резких границ, чтобы сформировать красивый, гармоничный силуэт со всех сторон.\n\n'
           || E'При комплексной проработке меняется не только контур ног — ягодицы визуально становятся более округлыми, а силуэт приобретает более женственные пропорции.\n\n'
           || E'❗️Процедура проводится без общего наркоза и без тяжёлой реабилитации❗️\n\n'
           || E'После процедуры вы самостоятельно встаёте и уходите домой.на своих уже худых ножках 💃\n\n'
           || E'Выше покажем, какие именно 7 зон входят в процедуру 🤍\n'
           || E'--- текст\n'
           || E'Круговая лазерная липосакция ног — это уникальная процедура, и доктор подходит к каждому пациенту индивидуально. Поскольку методика подходит не всем, нам важно сначала увидеть исходные формы и понять, сможем ли мы помочь именно в вашем случае.\n\n'
           || E'Пришлите, пожалуйста, фото ног прямо, сбоку и со спины — доктор проконсультирует и скажет будет ли эффективная наша процедура 🤍',
       updated_at = NOW()
 WHERE topic = 'legs_intro'
   AND body NOT LIKE '%все 7 зон ног%';
