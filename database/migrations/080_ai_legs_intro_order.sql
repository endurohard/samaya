-- Вступление про круговую липосакцию ног: схемы зон ПЕРЕД текстами.
--
-- Порядок задан владельцем: клиент должен сначала увидеть, какие именно
-- 7 зон прорабатываются, затем прочитать про методику, затем получить
-- просьбу прислать свои фото, и только после этого — цену. Прежний шаблон
-- начинался с просьбы сфотографироваться, то есть просил это раньше, чем
-- объяснял, что за процедура.
--
-- Переставляются ТОЛЬКО части этой темы. Текст про авторскую методику и
-- 7 зон живёт в отдельной теме legs_method, которую loadIntroParts()
-- дописывает в конец связки сама — дублировать его здесь нельзя, иначе
-- клиент получит один и тот же абзац дважды.
--
-- Фото идут первыми не случайно: legs_method заканчивается словами «Выше
-- показали, какие именно 7 зон входят в процедуру», и при обратном порядке
-- эта строка указывала бы в пустоту (в Direct новые сообщения ниже).
--
-- Условие WHERE защищает ручные правки владельца: если он уже переписал
-- тело через админку, миграция его не трогает.
UPDATE ai.reply_templates
   SET body = E'--- фото: legs-zones-front\n'
           || E'--- фото: legs-zones-back\n'
           || E'--- текст\n'
           || E'Круговая лазерная липосакция ног — это уникальная процедура, и доктор подходит к каждому пациенту индивидуально. Поскольку методика подходит не всем, нам важно сначала увидеть исходные формы и понять, сможем ли мы помочь именно в вашем случае.\n\n'
           || E'Пришлите, пожалуйста, фото ног прямо, сбоку и со спины — доктор проконсультирует и скажет будет ли эффективная наша процедура 🤍',
       updated_at = NOW()
 WHERE topic = 'legs_intro'
   AND body LIKE '%--- фото:%'
   AND body LIKE '%Пришлите, пожалуйста, фото ног%';
