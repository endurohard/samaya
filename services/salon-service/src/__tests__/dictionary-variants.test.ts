// Словарь услуг и городов: опечатки и сокращения из реальной переписки
// (Instagram + WhatsApp, год, ~13 тыс. сообщений клиентов). Каждая фраза
// ниже — дословно из диалога, где менеджер ответил по этой зоне/городу.
import { describe, it, expect } from 'vitest';
import { parseZones, parseCity, isSurveyAnswer, hasUnpricedZone } from '../ai/price';

describe('города: опечатки', () => {
  it.each(['Капийск 🥰вес 56 кг', 'Капицск', 'Касиийск, зона живота и бока', 'В карпийске можно узнать пожалуйста',
    'А если я приеду в Каспийке?', 'коспийск'])('%j → Каспийск', t => {
    expect(parseCity(t)).toBe('kaspiysk');
  });
  it.each(['Вы в маскве принимайте ?', 'Москаа , 119, холка'])('%j → Москва', t => {
    expect(parseCity(t)).toBe('moscow');
  });
  it('оба города с опечаткой — не угадываем', () => {
    expect(parseCity('И Москва и коспийск 70 кг')).toBeNull();
  });
});

describe('зоны: опечатки и разговорные названия', () => {
  it.each<[string, string]>([
    ['Город Каспийск,вес где то 67 -68 Хотела бы узнать ляжки', 'legs_circular'],
    ['Каспийск, вес 68,5, берда, колени', 'legs_circular'],
    ['Но ножки как слоновьи', 'legs_circular'],
    ['Добрый ночи можно узнать сколько будут стоить убрать 2_ подпородок ?', 'chin'],
    ['стоимость липосакции второго подродка', 'chin'],
    ['Ноги, живот и подборок, сделать более четкий овал', 'chin'],
    ['Сколько. Стоить. Подтянуть брили. В. Москве?', 'chin'],
    ['каспийск бриля подбородок', 'chin'],
    ['Я бы с первым липосакция авал лица хотела бы делать', 'chin'],
    ['Добрый день, а можно устать стоимость липосакции на ручки?', 'arms'],
    ['липосакцию рук и под мышки какая цена', 'arms'],
    ['Москва Вес 72 После кесарево фартук висит)', 'belly'],
    ['хотела узнат сцена лазерной лепосакци холки и жвот', 'belly'],
    ['Живот и бочка', 'waist'],
    ['Зона гольфе и внутренняя часть бедра', 'galife'],
    ['Каспийск , 175 , галфе', 'galife'],
    ['я не хочу увеличивать ягодницы или уменьшать', 'buttocks'],
  ])('%j → %s', (t, z) => {
    expect(parseZones(t)).toContain(z);
  });
});

describe('не цепляет посторонние слова', () => {
  it.each([
    'Бывают ли побочки?',                      // «бочк» внутри «побочки»
    'Скажите пожалуйста противопоказания и побочки',
    'И морфиус отдельно оплачивается?',       // Morpheus — не Contour Lift
    '300тр это будет с Morpheus 8?',
  ])('%j — без зоны', t => {
    expect(parseZones(t)).toEqual([]);
  });
});

describe('короткий ответ с опечаткой — ответ на опрос', () => {
  it.each(['Капийск', 'Ляжки', 'Фартук', 'Гольфе', 'Ручки', 'Подборок', 'В маскве'])('%j', t => {
    expect(isSurveyAnswer(t)).toBe(true);
  });
});

describe('Morpheus и FaceTite — к администратору', () => {
  it.each(['И морфиус отдельно оплачивается?', '300тр это будет с Morpheus 8?', 'А фейстайт сколько?'])('%j', t => {
    expect(hasUnpricedZone(t)).toBe(true);
  });
});
