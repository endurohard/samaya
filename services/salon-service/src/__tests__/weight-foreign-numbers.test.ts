// Вес нельзя вытаскивать из чужих чисел: телефона, суммы, процентов,
// доплаты. Иначе клиент получит цену по весу, которого не называл. Фразы —
// из реальной переписки за 30 дней.
import { describe, it, expect } from 'vitest';
import { parseWeight } from '../ai/price';

describe('вес не берётся из чужих чисел', () => {
  it.each([
    '89381568253',
    '+799****7195',
    'МАХ +799****4981',
    'Мой телефон 8 921 940 44 24',
    'Хорошо давайте перейдем на ватсап 89957818703',
    '89282009000 Хотела бы консультацию',
    '+7 928 200-90-00',
    'То что за 150000 тыс там только с подбородком работает врач ?',
    'Или если пришла в шубе 1 млн долларов, а если приехала на метро 1000 руб?',
    'Пока собираю информацию , но 100%есть желание сделать',
    'А +50 к стоимости Это что означает?',
    'Я после бариатрической операции скинула 60+ кг',
    'Это 300 тыс за руки?',
    'Цена 250 000 ₽ за живот?',
  ])('%j → нет веса', text => {
    expect(parseWeight(text)).toBeNull();
  });
});

describe('настоящий вес по-прежнему распознаётся', () => {
  it.each<[string, number]>([
    ['Москва 67 Руки', 67],
    ['Каспийск , 108, подбородок и руки', 108],
    ['57 к', 57],
    ['Москва 66 ко', 66],
    ['1. Каспийск 2. 72 3. Живот, бока', 72],
    ['Вес 89 Резких колебаний не было', 89],
    ['Москва, 125 кг, рост 171', 125],
    ['Каспийск 58кг Живот с рубцом от кесарева', 58],
    ['Мой вес 63,5', 63.5],
    ['Вес 70, телефон 89282009000', 70],
    // Нумерованный ответ на опрос и приблизительный вес — не телефон и не доплата.
    ['1. Москва 2.113', 113],
    ['1) без разницы 2) 112 3) ноги', 112],
    ['1 Москва 2 105 3 живот и руки', 105],
    ['Здравствуйте! 1 . Каспийск 1.110кг 3.Живот ,руки ноги ,', 110],
    ['Каспийск Вес 63,800', 63.8],
    ['Город Каспийск Вес 78 +/- 2 кг', 78],
    ['Вес 66+-', 66],
  ])('%j → %d', (text, w) => {
    expect(parseWeight(text)).toBe(w);
  });

  it.each(['200+50', 'я рассчитывала в пределах 80-100 тыс', 'В Москве цена 350 или 350+150 и 100?'])('%j — сумма, не вес', text => {
    expect(parseWeight(text)).toBeNull();
  });
});
