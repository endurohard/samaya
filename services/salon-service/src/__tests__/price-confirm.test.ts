// Подтверждение прежних города и веса (возврат клиента в течение недели).
//
// Требование владельца: клиент вернулся через несколько дней — не
// спрашивать всё заново, а уточнить, не изменились ли данные. Ответил
// «верно» — считаем по прежним; «нет» — спрашиваем новые.
//
// Фразы взяты как их пишут в живой переписке: короткие, с опечатками и
// без знаков препинания.
import { describe, it, expect } from 'vitest';
import { parseConfirmation } from '../ai/price';

describe('parseConfirmation', () => {
  it.each([
    'да',
    'Да',
    'да, всё верно',
    'всё верно',
    'все верно',
    'верно',
    'правильно',
    'всё так',
    'те же',
    'без изменений',
    'не изменился',
    'ничего не изменилось',
    'прежние',
    'актуально',
    '+',
  ])('«%s» — подтверждение', (t) => {
    expect(parseConfirmation(t)).toBe(true);
  });

  it.each([
    'нет',
    'Нет',
    'нет, изменился',
    'неверно',
    'не верно',
    'вес изменился',
    'уже не Москва',
    'поменялся',
    'теперь 80',
    'другой город',
  ])('«%s» — данные изменились', (t) => {
    expect(parseConfirmation(t)).toBe(false);
  });

  it('отрицание сильнее согласия в одной фразе', () => {
    // «да нет» — разговорное отрицание; в «нет, да, 80» тоже главное «нет».
    expect(parseConfirmation('да нет, поменялся')).toBe(false);
    expect(parseConfirmation('нет, уже другой вес')).toBe(false);
  });

  it.each([
    'Сколько стоит липосакция ног?',
    'Каспийск',
    '80',
    'а когда можно записаться',
    '',
  ])('«%s» — не ответ на этот вопрос', (t) => {
    expect(parseConfirmation(t)).toBeNull();
  });

  it('эмодзи не мешают разобрать ответ', () => {
    expect(parseConfirmation('да 🤍')).toBe(true);
    expect(parseConfirmation('нет 😔')).toBe(false);
  });
});
