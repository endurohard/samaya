// Ответ на вопросы ценового опроса: сообщение состоит только из города,
// веса и зон. Пока опрос идёт, такое сообщение разбирает сам опрос, а не
// Jev: 4 ноября 99 таких ответов («Москва, вес 73», «Живот и руки») ушли в
// manual_review, и бот переспрашивал то, на что клиент уже ответил.
// Фразы — из реальной переписки.
import { describe, it, expect } from 'vitest';
import { isSurveyAnswer } from '../ai/price';

describe('ответ на вопросы опроса', () => {
  it.each([
    'Живот и руки', '90 кг', 'Вес 53 Москва', 'Зона ног ляжки Бедра', 'Москва, вес 73',
    'Москва Подбородок', 'Ноги , бедра , живот подбородок', 'Москвы 75', 'москва 55 кг',
    'Каспийск , 71 вес', 'Каспийск , руки , живот , ноги', 'Москва 82кг',
    'Москва,подбородок,область живота и ног', '85 кг, рост 165', 'Мой вес 68',
    'Каспийск Вес 69 70кг', 'Москва. Живот.', 'Интересует подбородок , ноги , руки 🫣',
    'Ноги интересует тоже', 'Живот и бока', 'Второй подбородок Каспийск',
    'внутренняя поверхность бедра', 'Москва Внутренняя часть бедра', 'Каспийск, вес 105 кг',
    'Здравствуйте, Москва, 64 кг, ноги', 'Москва\n65',
  ])('%j — ответ опросу', text => {
    expect(isSurveyAnswer(text)).toBe(true);
  });

  it.each([
    '89120363789',                                  // телефон — менеджеру
    '+7 912 036-37-89',
    'Москва, а сколько длится реабилитация?',       // вопрос — классификатору
    'Хочу записаться на живот',
    'Можно ли при ГВ делать руки?',
    'Здравствуйте',                                 // нет ни одного поля
    'Спасибо',
    'и тот и тот',
    'мне без разницы',
    'Сколько стоит эпиляция рук?',
    'Москва и Каспийск',                             // два города — не ответ
    'Липосакция рук',                                // новая услуга — через классификатор
    'Лазерная липосакция холки',
  ])('%j — не ответ опросу', text => {
    expect(isSurveyAnswer(text)).toBe(false);
  });
});
