// Каждая услуга прайса распознаётся ровно как одна зона.
// Подстроки не должны добавлять соседнюю услугу: «лобок» раньше содержал
// корень «бок» и ошибочно превращался в набор «талия + лобок».
import { describe, it, expect } from 'vitest';
import { parseZones } from '../ai/price';

const cases: Array<[string, string]> = [
  ['Подбородок', 'chin'],
  ['Contour Lift', 'contour_lift'],
  ['Холка', 'holka'],
  ['Руки', 'arms'],
  ['Живот', 'belly'],
  ['Талия', 'waist'],
  ['Ноги', 'legs_circular'],
  ['Внутренняя поверхность ног до колен', 'inner_legs'],
  ['Галифе', 'galife'],
  ['Лобок', 'pubis'],
  ['Голень', 'shin'],
  ['Уменьшение ягодиц', 'buttocks'],
];

describe('распознавание всех услуг прайса', () => {
  it.each(cases)('%s → только %s', (phrase, zone) => {
    expect(parseZones(phrase)).toEqual([zone]);
  });

  it.each(['бок', 'бока', 'на боках', 'убрать бока'])('%s → талия', (phrase) => {
    expect(parseZones(phrase)).toEqual(['waist']);
  });
});

// Решение владельца: голые «ноги»/«бёдра» — это круговая липосакция (все 7
// зон). Но если клиент назвал ЛОКАЛЬНУЮ зону ног, круговая к ней не
// добавляется: 4 ноября «внутренняя поверхность бедра» давала расчёт
// «300 000 + 700 000» и схемы круговой процедуры. Фразы — из реальной
// переписки.
describe('ноги: общее слово — круговая, локальная зона — только она', () => {
  it.each<[string, string[]]>([
    ['Ноги', ['legs_circular']],
    ['Бёдра', ['legs_circular']],
    ['Каспийск Зона ног ляжки Бедра', ['legs_circular']],
    ['Лазерная липосакция ‼️НОГ‼️', ['legs_circular']],
    ['круговая сколько стоит', []],
    ['Круговая липосакция ног', ['legs_circular']],
    ['внутренняя поверхность бедра', ['inner_legs']],
    ['И еще скажи стоимость липосакции внутренней стороны бедра?', ['inner_legs']],
    ['хочу убрать внутреннюю часть бедер Стоимость интересует в Каспийске', ['inner_legs']],
    ['Здравствуйте А зона бедра внутренняя сколько стоит', ['inner_legs']],
    ['Галифе и внутренняя', ['inner_legs', 'galife']],
    ['Зона галифе , немного живот , внутрення ватт бедра', ['inner_legs', 'belly', 'galife']],
    ['Добрый день! Уточните стоимость липосакции голени', ['shin']],
    ['икры', ['shin']],
    // Голень — ниже колена, круговая — «от колен и выше»: бёдра и голени
    // вместе это две разные зоны, а не локальная коррекция бедра.
    ['Каспийск Бедра и голени', ['legs_circular', 'shin']],
    ['Голень и внутренняя часть бедра', ['inner_legs', 'shin']],
  ])('%s → %j', (phrase, zones) => {
    expect([...parseZones(phrase)].sort()).toEqual([...zones].sort());
  });

  it('явная круговая вместе с локальной зоной сохраняет обе', () => {
    expect([...parseZones('круговая бедер и отдельно зона галифе')].sort())
      .toEqual(['galife', 'legs_circular']);
  });
});
