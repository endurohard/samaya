// Ответ из НЕСКОЛЬКИХ сообщений: текст, фото, текст.
//
// Зачем отдельный тип вместо одной строки: в Instagram Direct подписи под
// вложением нет — каждое фото уходит отдельным сообщением. Схема «ответ =
// одна строка» для сценариев вида «объясни и покажи зоны» не годится
// физически, и попытка склеить всё в текст теряет сами картинки.
//
// Порядок частей — это смысл сообщения («выше показали 7 зон» обязано идти
// ПОСЛЕ фотографий), поэтому части хранятся списком, а не набором полей.

export type ReplyPart =
  | { type: 'text'; text: string }
  | { type: 'image'; asset: string };

/**
 * Разобрать тело шаблона на части.
 *
 * Разметка — строки-разделители, а не JSON: владелец правит эти тексты в
 * админке, и JSON он сломает первой же правкой, после чего ответ клиенту
 * пропадёт целиком.
 *
 *     --- текст
 *     Круговая лазерная липосакция ног — это уникальная процедура…
 *     --- фото: legs-zones-front
 *     --- фото: legs-zones-back
 *     --- текст
 *     Уникальная авторская методика…
 *
 * Имя фото — ключ файла, который лежит рядом с сервисом канала
 * (instagram-service/assets). В шаблоне намеренно имя, а не ссылка: ссылка
 * с подписью живёт минуты, а картинки одни и те же месяцами.
 */
export function parseParts(body: string): ReplyPart[] {
  const lines = String(body || '').split(/\r?\n/);
  const parts: ReplyPart[] = [];
  let buf: string[] = [];

  const flushText = () => {
    const text = buf.join('\n').trim();
    buf = [];
    if (text) parts.push({ type: 'text', text });
  };

  for (const line of lines) {
    const m = line.match(/^\s*---\s*(текст|фото)\s*(?::\s*(.*))?$/i);
    if (!m) { buf.push(line); continue; }
    // Любой разделитель закрывает накопленный текст — иначе текст первой
    // части приклеился бы ко второй.
    flushText();
    if (m[1].toLowerCase() === 'фото') {
      // Имя файла ограничено латиницей: оно попадает в путь на диске, и
      // «../» в нём увело бы чтение за пределы каталога картинок.
      const asset = String(m[2] || '').trim().toLowerCase();
      if (/^[a-z0-9][a-z0-9._-]{0,63}$/.test(asset)) parts.push({ type: 'image', asset });
    }
  }
  flushText();
  return parts;
}
